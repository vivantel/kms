#!/usr/bin/env python3
"""Generate the admission eval: one test per development case in cases.tsv (the knowledge-boundary
plan's 66 cases; the sealed held-out set is not here), each asking the agent to apply the artifact
model's Admission section to one change and name the record it would create.

Usage: build.py            write promptfooconfig.yaml
       build.py --check    fail if the committed file differs from what this would write
"""

import csv
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CLASSES = ["none", "fact", "decision", "guardrail", "procedure"]

PROMPT = (
    "A work session just ended. One change came out of it: {{case}} "
    "Run the first check of the `capture` skill on this change only. Apply the Admission section of the artifact model, "
    "and do not create or edit any file. End your response with exactly one line, `ADMISSION:` followed by the record "
    "this change would become: one of none, fact, decision, guardrail, procedure."
)


def cases():
    with open(HERE / "cases.tsv", encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f, delimiter="\t"))


def build():
    tests = "\n".join(
        f'  - description: "{c["id"]}"\n    vars:\n      case: {c["case"]!r}'.replace("\\'", "''") for c in cases())
    return (
        "# Generated by build.py; do not edit. Run: npx promptfoo eval -c evals/admission/promptfooconfig.yaml --repeat 5 -o out.json\n"
        "# Score: python3 evals/admission/score.py out.json\n"
        'description: "kms admission: does the agent record only changes that pass the admission test"\n'
        f"prompts:\n  - >\n    {PROMPT}\n"
        "providers:\n  - id: \"exec:../providers/kilo-runner.sh\"\n    config:\n      fixture_dir: \"evals/admission/fixture\"\n"
        "      model: \"nvidia/nvidia/nemotron-3.5-lightning-30b-a3b\"\n      timeout_seconds: 480\n"
        "defaultTest:\n  assert:\n    - type: regex\n      value: \"ADMISSION:[ \\\\t]*`?(none|fact|decision|guardrail|procedure)`?[ \\\\t.]*$\"\n"
        f"tests:\n{tests}\n")


def main():
    out = build()
    p = HERE / "promptfooconfig.yaml"
    if "--check" in sys.argv:
        if not p.exists() or p.read_text(encoding="utf-8") != out:
            raise SystemExit("out of date: promptfooconfig.yaml")
        return
    p.write_text(out, encoding="utf-8")


if __name__ == "__main__":
    main()
